#5. Function definitions -----
lookup_diagnostic <- function(diagnostics, metric, country_code, stratum,
                              statistic) {
  is_match <- diagnostics$metric == metric &
    diagnostics$country == country_code &
    diagnostics$stratum == stratum &
    diagnostics$statistic == statistic
  matched_values <- diagnostics$value[is_match]
  if (length(matched_values) == 0) {
    return(NA_character_)
  }
  matched_values[1]
}

# One "| label | DE | JP |" row per row specification.
format_compare_rows <- function(diagnostics, row_specs) {
  pmap_chr(row_specs, \(label, metric, stratum, statistic) {
    sprintf(
      "| %s | %s | %s |", label,
      lookup_diagnostic(diagnostics, metric, "DE", stratum, statistic),
      lookup_diagnostic(diagnostics, metric, "JP", stratum, statistic)
    )
  })
}

format_crux_rows <- function(diagnostics, countries, strata_names) {
  crux_grid <- expand_grid(country_code = countries, stratum = strata_names)
  pmap_chr(crux_grid, \(country_code, stratum) {
    lookup_crux <- function(statistic) {
      lookup_diagnostic(diagnostics, "crux", country_code, stratum, statistic)
    }
    sprintf(
      "| %s | %s | %s | %s | %s | %s |", country_code, stratum,
      lookup_crux("n"), lookup_crux("pct_at_15"),
      lookup_crux("pct_at_mode"), lookup_crux("entropy")
    )
  })
}

build_diagnostics_markdown <- function(diagnostics, countries, strata_names) {
  c(
    "# SWD country diagnostics (DE vs JP)",
    "",
    paste0(
      "Generated by `R_SWD/utils/07_country_diagnostics.R` ",
      "(read-only; not part of the main pipeline)."
    ),
    "",
    "## 1. Funnel and acceptance",
    "",
    "| | DE | JP |",
    "|---|---|---|",
    format_compare_rows(diagnostics, FUNNEL_ROWS),
    "",
    "## 2. Response quality / engagement",
    "",
    "| | DE | JP |",
    "|---|---|---|",
    format_compare_rows(diagnostics, QUALITY_ROWS),
    "",
    "## 3. SWD dispersion among usable respondents",
    "",
    "Normalized entropy: 0 = single spike, 1 = perfectly flat.",
    "",
    "| | DE | JP |",
    "|---|---|---|",
    format_compare_rows(diagnostics, DISPERSION_ROWS),
    "",
    "## 4. Comprehension gate (important caveat)",
    "",
    "CO02 (relapse without treatment) and CO03 (side effects) are HARD GATES: no respondent",
    "reached the staircase with either wrong, so the entire usable SWD sample is already",
    "comprehension-screened by design. CO01 (multi-select symptoms) is lenient (a few passed",
    "with an imperfect selection). Wrong answers among usable respondents:",
    "",
    "| | DE | JP |",
    "|---|---|---|",
    format_compare_rows(diagnostics, GATE_ROWS),
    "",
    "Because CO02/CO03 gate the staircase, the `comp_pass`/`comp_fail` split below only",
    "reflects the non-gated CO01 selection and is NOT a real comprehension contrast; use the",
    "`time_slow`/`time_fast` split as the within-sample engagement axis instead.",
    "",
    "## 5. Crux: does higher-quality JP sharpen toward SWD=15?",
    "",
    "For each stratum: n, % at SWD=15, % at modal value, normalized entropy.",
    "",
    "| country | stratum | n | %@15 | %@mode | entropy |",
    "|---|---|---|---|---|---|",
    format_crux_rows(diagnostics, countries, strata_names),
    DIAGNOSTICS_READING
  )
}

